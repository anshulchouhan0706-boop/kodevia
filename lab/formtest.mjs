import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
let posted = null; p.on('request', r => { if (r.url().includes('script.google.com')) posted = { method: r.method(), body: r.postData() }; });
await p.goto('http://localhost:4500/#start', { waitUntil: 'networkidle' }); await p.waitForTimeout(1200);
await p.evaluate(() => document.getElementById('lead').scrollIntoView({ behavior: 'instant' }));
await p.fill('[name=name]', 'TEST (website form, please delete)');
await p.fill('[name=phone]', '9244774704');
await p.fill('[name=email]', 'test@kodevia.com');
await p.fill('[name=company]', 'Kodevia');
await p.selectOption('[name=service]', 'Mobile app (iOS and Android)');
await p.selectOption('[name=budget]', 'Not sure yet');
await p.selectOption('[name=timeline]', 'Just exploring');
await p.selectOption('[name=source]', 'Other');
await p.fill('[name=message]', 'End-to-end test of the Book a free demo form.');
await p.check('[name=consent]');
await p.click('.lead__submit');
await p.waitForSelector('.lead__done:not([hidden])', { timeout: 20000 });
await p.waitForTimeout(800);
await p.screenshot({ path: 'lab/form-done.png' });
console.log('request sent:', posted ? posted.method + ' ' + decodeURIComponent(posted.body.replace(/\+/g, ' ')) : 'none');
console.log('thank-you shown:', await p.evaluate(() => !document.querySelector('.lead__done').hidden));
console.log(errs.length ? errs.join('\n') : 'no page errors');
await b.close();
